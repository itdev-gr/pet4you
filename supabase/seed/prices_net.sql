-- ============================================================================
-- Μετατροπή τιμών σε ΚΑΘΑΡΕΣ (προ ΦΠΑ).
--
-- Το store.product_variants.price είναι καθαρή τιμή κατά το συμβόλαιο του
-- dashboard: το create_order_v1 προσθέτει τον ΦΠΑ ανά γραμμή με βάση το
-- products.tax_class. Το storefront εμφανίζει τη μεικτή τιμή (net × 1,24).
--
-- Οι καθαρές τιμές επιλέχθηκαν ώστε η μεικτή να πέφτει ΑΚΡΙΒΩΣ στην τιμή
-- ραφιού του design. Εξαίρεση: 6,90 € δεν είναι επιτεύξιμη με 2 δεκαδικά
-- στην καθαρή τιμή (5,56 → 6,89 · 5,57 → 6,91) — κρατάμε 5,56 → 6,89 €.
--
-- Ιδιοδύναμο: τρέχει μόνο σε τιμές που ταιριάζουν στη στήλη gross.
-- ============================================================================

create temporary table if not exists _price_map (gross numeric(10,2), net numeric(10,2));
truncate _price_map;
insert into _price_map (gross, net) values
  (5.90, 4.76), (6.90, 5.56), (7.90, 6.37), (8.90, 7.18), (9.90, 7.98),
  (11.90, 9.60), (12.90, 10.40), (14.50, 11.69), (14.90, 12.02),
  (19.90, 16.05), (21.90, 17.66), (22.90, 18.47), (24.90, 20.08),
  (29.90, 24.11), (34.50, 27.82), (39.90, 32.18), (44.90, 36.21), (49.90, 40.24);

update store.product_variants v
set price = m.net
from _price_map m
where v.price = m.gross;

update store.product_variants v
set compare_at_price = m.net
from _price_map m
where v.compare_at_price = m.gross;
